/* ---------- Theme Switcher (Dark / Light Mode) ---------- */
(function () {
  const themeToggle = document.getElementById('themeToggle');
  const themeSun = document.getElementById('themeSun');
  const themeMoon = document.getElementById('themeMoon');
  
  function applyTheme(theme) {
    if (theme === 'light') {
      document.documentElement.setAttribute('data-theme', 'light');
      if (themeSun) themeSun.classList.remove('hidden');
      if (themeMoon) themeMoon.classList.add('hidden');
    } else {
      document.documentElement.removeAttribute('data-theme');
      if (themeSun) themeSun.classList.add('hidden');
      if (themeMoon) themeMoon.classList.remove('hidden');
    }
    localStorage.setItem('va_theme', theme);
  }

  const savedTheme = localStorage.getItem('va_theme') || 'dark';
  applyTheme(savedTheme);

  if (themeToggle) {
    themeToggle.addEventListener('click', () => {
      const current = document.documentElement.getAttribute('data-theme') === 'light' ? 'light' : 'dark';
      const next = current === 'light' ? 'dark' : 'light';
      applyTheme(next);
      showToast('THEME TOGGLED', next === 'light' ? 'Light mode activated.' : 'Dark mode activated.');
    });
  }
})();


/* ---------- Opportunity Intake Dropdown ---------- */
(function () {
  const btn    = document.getElementById('oppDropdownBtn');
  const menu   = document.getElementById('oppDropdownMenu');
  const label  = document.getElementById('oppDropdownLabel');
  const hidden = document.getElementById('fOppType');
  if (!btn || !menu) return;

  function openMenu() {
    menu.classList.add('open');
    btn.setAttribute('aria-expanded', 'true');
  }

  function closeMenu() {
    menu.classList.remove('open');
    btn.setAttribute('aria-expanded', 'false');
  }

  btn.addEventListener('click', (e) => {
    e.stopPropagation();
    const isOpen = menu.classList.contains('open');
    isOpen ? closeMenu() : openMenu();
  });

  // Close when clicking outside
  document.addEventListener('click', (e) => {
    if (!btn.contains(e.target) && !menu.contains(e.target)) {
      closeMenu();
    }
  });

  // Close on Escape key
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeMenu();
  });

  // Handle option selection
  menu.querySelectorAll('.opp-option').forEach(opt => {
    opt.addEventListener('click', () => {
      const value = opt.dataset.value;

      // Update hidden input
      if (hidden) hidden.value = value;

      // Update trigger label
      if (label) {
        label.innerHTML = `
          <span class="w-1.5 h-1.5 rounded-full bg-[var(--accent)]"></span>
          <span>${value}</span>`;
      }

      // Update selected state
      menu.querySelectorAll('.opp-option').forEach(o => {
        o.classList.remove('selected');
        const check = o.querySelector('.check-icon');
        if (check) check.classList.add('hidden');
      });
      opt.classList.add('selected');
      const ck = opt.querySelector('.check-icon');
      if (ck) ck.classList.remove('hidden');

      closeMenu();
    });
  });
})();

// Smooth scrolling for internal anchor links (safe for file:// and http/https protocols)
document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function(e) {
      const targetId = this.getAttribute('href');
      if (targetId && targetId !== '#' && targetId.length > 1) {
        const targetElement = document.querySelector(targetId);
        if (targetElement) {
          e.preventDefault();
          targetElement.scrollIntoView({ behavior: 'smooth' });
          if (window.location.protocol !== 'file:') {
            history.pushState(null, '', targetId);
          }
        }
      }
    });
  });
});

