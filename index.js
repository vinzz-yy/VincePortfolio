function rrect(g, x, y, w, h, r) {
  g.beginPath();
  g.moveTo(x + r, y);
  g.arcTo(x + w, y, x + w, y + h, r);
  g.arcTo(x + w, y + h, x, y + h, r);
  g.arcTo(x, y + h, x, y, r);
  g.arcTo(x, y, x + w, y, r);
  g.closePath();
}
function txt(g, s, x, y, font, color, align) {
  g.font = font; g.fillStyle = color;
  if (align) g.textAlign = align;
  g.fillText(s, x, y);
  if (align) g.textAlign = 'left';
}
