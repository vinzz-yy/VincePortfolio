/* ---------- avatars & portrait ---------- */
function makeAvatar(ii, idx) {
  const S = 160, c = makeCanvas(S, S), g = c.getContext('2d');
  g.fillStyle = '#0f0f0f'; g.fillRect(0, 0, S, S);
  const mode = idx % 4;
  if (mode === 0) {
    g.font = '11px "JetBrains Mono", monospace';
    for (let i = 0; i < 34; i++) { g.fillStyle = 'rgba(190,190,190,' + (0.05 + Math.random() * 0.09) + ')'; g.fillText(rc(), Math.random() * S, Math.random() * S); }
  } else if (mode === 1) {
    g.strokeStyle = 'rgba(190,190,190,.10)';
    for (let k = 0; k <= S; k += 16) { g.beginPath(); g.moveTo(k, 0); g.lineTo(k, S); g.stroke(); g.beginPath(); g.moveTo(0, k); g.lineTo(S, k); g.stroke(); }
  } else if (mode === 2) {
    g.strokeStyle = 'rgba(190,190,190,.10)';
    for (let k = -S; k < S; k += 18) { g.beginPath(); g.moveTo(k, 0); g.lineTo(k + S, S); g.stroke(); }
  } else {
    g.font = '11px "JetBrains Mono", monospace';
    for (let i = 0; i < 40; i++) { g.fillStyle = 'rgba(190,190,190,' + (0.05 + Math.random() * 0.10) + ')'; g.fillText(Math.random() < .5 ? '0' : '1', Math.random() * S, Math.random() * S); }
  }
  g.textAlign = 'center'; g.textBaseline = 'middle';
  g.font = '700 58px Oswald, Arial'; g.fillStyle = '#f2f2f2'; g.fillText(ii, S / 2, S / 2 - 6);
  g.fillStyle = '#FF5400'; g.fillRect(S / 2 - 15, S / 2 + 30, 30, 4);
  g.textAlign = 'left'; g.textBaseline = 'alphabetic';
  return c.toDataURL('image/png');
}

